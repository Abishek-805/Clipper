// Run only against a disposable server and an explicitly supplied synthetic source.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.CLIPPER_PLAYWRIGHT_MODULE || 'playwright');
(async () => {
 const source = process.env.CLIPPER_AUDIT_SOURCE;
 assert(source, 'Set CLIPPER_AUDIT_SOURCE to a seeded synthetic recording');
 const base = process.env.CLIPPER_UI_URL;
 assert(base, 'Set CLIPPER_UI_URL to a disposable loopback server');
 const browser = await chromium.launch({executablePath: process.env.CLIPPER_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true});
 const checks = [], errors = [];
 try {
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
  page.setDefaultTimeout(20000);
  page.on('response', async r => {if(r.status()>=400)console.error('HTTP',r.status(),r.url(),await r.text());});
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', e => { if(e.type() === 'error') errors.push(e.text()); });
  await page.goto(base);
  await page.getByRole('button', {name: 'New recording', exact: true}).click();
  await page.locator('#source').fill(source);
  await page.locator('#inspect').click();
  await page.waitForFunction(() => !document.querySelector('#manual').disabled);
  await page.locator('#source-profile').selectOption('broadcast');
  await page.locator('#manual-panel summary').click();
  await page.locator('#load-transcript').click();
  await page.locator('#transcript-rows button').first().waitFor();
  await page.locator('#transcript-query').fill('context');
  assert.equal(await page.locator('#transcript-rows button').count(), 1);
  await page.locator('#transcript-rows button').first().click();
  assert.equal(await page.locator('#manual-start').inputValue(), '1.200');
  assert.equal(await page.locator('#manual-end').inputValue(), '2.400');
  console.log('Verified step',checks.length+1);checks.push('seeded transcript search and source interval');
  await page.locator('#manual-start').fill('0');
  await page.locator('#manual-end').fill('3');
  await page.locator('#source-preview').click();
  await page.waitForFunction(() => document.querySelector('#source-player').getAttribute('src'));
  await page.locator('#source-player').evaluate(async v => {v.muted=true; await v.play(); await new Promise(r=>setTimeout(r,300)); v.pause();});
  console.log('Verified step',checks.length+1);checks.push('selected-track source preview playback');
  await page.waitForFunction(() => !document.querySelector('#manual').disabled);
  const created = page.waitForResponse(r=>r.url().endsWith('/api/manual')&&r.request().method()==='POST');
  await page.locator('#manual').click();
  const job = await (await created).json();
  await page.waitForFunction(id=>document.querySelector('#result').textContent.includes(id), job.job_id);
  await page.locator('.draft .caption-row textarea').first().waitFor({timeout: 30000});
  console.log('Draft rows loaded');
  const cue = page.locator('.draft .caption-row textarea').first();
  await cue.fill('Owner corrected caption.');
  await page.locator('.save-edit').first().click();
  console.log('Edit submitted',await page.locator('#edit-status-0').innerText());
  await page.waitForFunction(() => document.querySelector('#edit-status-0')?.textContent === 'Complete', {}, {timeout: 30000});
  assert.equal(await cue.inputValue(), 'Owner corrected caption.');
  const firstState = await (await page.request.get(base+'/api/status')).json();
  const firstRevision = firstState.report.drafts[0].media_revision;
  console.log('Verified step',checks.length+1);checks.push('first caption edit rendered');
  await page.locator('#position-0').selectOption('center-lower');
  await page.locator('#start-0').fill('0.1');
  await page.locator('#start-0').dispatchEvent('input');
  await page.locator('.save-edit').first().click();
  console.log('Edit submitted',await page.locator('#edit-status-0').innerText());
  await page.waitForFunction(() => document.querySelector('#edit-status-0')?.textContent === 'Complete', {}, {timeout: 30000});
  const secondState = await (await page.request.get(base+'/api/status')).json();
  assert.notEqual(secondState.report.drafts[0].media_revision, firstRevision);
  assert.equal(await cue.inputValue(), 'Owner corrected caption.');
  console.log('Verified step',checks.length+1);checks.push('second trim/placement edit retained corrections and changed media revision');
  await page.reload();
  await page.locator('.draft .caption-row textarea').first().waitFor();
  assert.equal(await page.locator('.draft .caption-row textarea').first().inputValue(), 'Owner corrected caption.');
  await page.locator('.draft video').first().evaluate(async v => {v.muted=true;await v.play();await new Promise(r=>setTimeout(r,300));v.pause();});
  console.log('Verified step',checks.length+1);checks.push('reload retained captions and playable portrait');
  await page.locator('[data-export]').first().click();
  await page.waitForFunction(() => document.querySelector('#export-0')?.textContent.includes('Exports'));
  console.log('Verified step',checks.length+1);checks.push('validated delivery export');
  assert.deepEqual(errors, []);
  fs.mkdirSync('output/playwright', {recursive:true});
  await page.screenshot({path:'output/playwright/audit-workflow.png',fullPage:true});
  fs.writeFileSync('output/playwright/audit-workflow-result.json',JSON.stringify({checks,errors,job:secondState.job_id,firstRevision,secondRevision:secondState.report.drafts[0].media_revision,transcript:'SEEDED; no inference; synthetic tone audio'},null,2));
  console.log(`PASS: ${checks.length} audit workflow checks; no page/console errors`);
 } finally {await browser.close();}
})().catch(e => {console.error(e);process.exitCode=1;});
